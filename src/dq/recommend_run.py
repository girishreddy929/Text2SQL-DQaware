"""Write suggested DQ rules for one source, based on dq.latest_profiles.

python -m src.dq.recommend_run [--source olist] [--min-confidence low|medium|high] [--verify]
Output: config/dq_suggestions/<source>.yaml (review it, copy accepted rules to config/dq_rules/)
"""

from __future__ import annotations

import argparse
from collections import Counter

import yaml
from sqlalchemy import text

from config.settings import PROJECT_ROOT
from src.common.db import get_admin_engine, get_reader_engine
from src.common.logging import get_logger
from src.dq.recommender import Suggestion, recommend_all
from src.dq.rules_models import RuleFileError, check_db, columns_of, load_rules
from src.dq.runner import execute_rule

log = get_logger(__name__)
OUT_DIR = PROJECT_ROOT / "config" / "dq_suggestions"
RANK = {"low": 0, "medium": 1, "high": 2}
PROFILE_SQL = text("""
    SELECT schema_name, table_name, column_name, type_category, row_count, null_count,
           null_pct, distinct_count, distinct_pct, min_value, max_value,
           min_length, max_length, top_values
    FROM dq.latest_profiles WHERE source_id = :source
    ORDER BY schema_name, table_name, ordinal_position""")


def load_profiles(source: str) -> list[dict]:
    with get_admin_engine().connect() as conn:
        return [
            dict(r) for r in conn.execute(PROFILE_SQL, {"source": source}).mappings()
        ]


def existing_rules(source: str) -> tuple[set, set]:
    """(table, columns, type) keys and ids of the rules already in config/dq_rules."""
    mine = [r for r in load_rules() if r.source_id == source]
    return {(r.table, tuple(columns_of(r)), r.type) for r in mine}, {r.id for r in mine}


def is_duplicate(s: Suggestion, keys: set, ids: set) -> bool:
    r = s.rule
    return r["id"] in ids or (r["table"], (r["column"],), r["type"]) in keys


def render(source: str, suggestions: list[Suggestion]) -> str:
    lines = [
        "# Suggested rules, generated by src.dq.recommend_run.",
        "# Review them, then copy the ones you accept into config/dq_rules/.",
        yaml.safe_dump({"source_id": source}).strip(),
        "rules:",
    ]
    for s in suggestions:
        lines.append(f"  # [{s.confidence}] {s.reason}")
        body = yaml.safe_dump([s.rule], sort_keys=False, allow_unicode=True, width=1000)
        lines += ["  " + ln for ln in body.splitlines()]
    return "\n".join(lines) + "\n"


def verify(rules: list, timeout_s: int) -> int:
    """Run every suggestion as t2s_reader (nothing is stored). Returns how many did not pass."""
    engine, bad = get_reader_engine(), 0
    for r in rules:
        res = execute_rule(engine, r, timeout_s)
        if res["status"] != "passed":
            bad += 1
            print(
                f"  NOT PASSED {r.id}: {res['status']} {res.get('error_message') or ''}"
            )
    return bad


def main() -> int:
    ap = argparse.ArgumentParser(description="Suggest DQ rules from stored profiles")
    ap.add_argument("--source", default="olist")
    ap.add_argument("--min-confidence", choices=list(RANK), default="low")
    ap.add_argument(
        "--verify", action="store_true", help="run each suggestion (no writes)"
    )
    ap.add_argument("--timeout", type=int, default=120)
    args = ap.parse_args()

    profiles = load_profiles(args.source)
    if not profiles:
        log.error(
            "No profiles for %s. Run: python -m src.dq.profiler --source %s",
            args.source,
            args.source,
        )
        return 1
    keys, ids = existing_rules(args.source)
    found = [
        s
        for s in recommend_all(profiles)
        if RANK[s.confidence] >= RANK[args.min_confidence]
    ]
    fresh = [s for s in found if not is_duplicate(s, keys, ids)]
    print(
        f"Profiles read: {len(profiles)} | suggested: {len(found)} | "
        f"already covered by existing rules: {len(found) - len(fresh)} | new: {len(fresh)}"
    )
    print("By type:      ", dict(Counter(s.rule["type"] for s in fresh)))
    print("By confidence:", dict(Counter(s.confidence for s in fresh)))
    if not fresh:
        return 0

    OUT_DIR.mkdir(exist_ok=True)
    path = OUT_DIR / f"{args.source.replace(':', '_')}.yaml"
    path.write_text(render(args.source, fresh), encoding="utf-8")
    print(f"Wrote {path.relative_to(PROJECT_ROOT)}")

    try:  # self-check 1: the file loads through the normal rule loader
        loaded = [r for r in load_rules(OUT_DIR) if r.source_id == args.source]
    except RuleFileError as exc:
        print(exc)
        return 1
    problems = check_db(
        loaded
    )  # self-check 2: tables and columns exist in the database
    print(
        f"Reloaded {len(loaded)}/{len(fresh)} rules; database check problems: {len(problems)}"
    )
    for p in problems[:10]:
        print("  ", p)
    bad = verify(loaded, args.timeout) if args.verify else 0
    if args.verify:
        print(
            f"Verified by running them: {len(loaded) - bad} passed, {bad} did not pass"
        )
    return 1 if (len(loaded) != len(fresh) or problems or bad) else 0


if __name__ == "__main__":
    raise SystemExit(main())
