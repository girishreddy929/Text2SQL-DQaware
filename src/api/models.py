# src/api/models.py
from pydantic import BaseModel, Field
from typing import Any


class QueryRequest(BaseModel):
    question: str = Field(..., description="The user's natural language question.")
    source_id: str = Field(
        default="olist",
        description="The database source ID (e.g., 'olist' or 'bird:california_schools').",
    )
    chat_history: list[dict] = Field(
        default_factory=list, description="Previous chat messages for context."
    )


class QueryResponse(BaseModel):
    intent: str = Field(
        ..., description="The classified intent (e.g., data_question, dq_question)."
    )
    generated_sql: str | None = Field(
        default=None, description="The SQL query generated by the agent."
    )
    selected_tables: list[str] = Field(
        default_factory=list, description="Tables used to answer the query."
    )
    execution_result: list[dict] = Field(
        default_factory=list,
        description="The raw data rows returned from the database.",
    )
    dq_warnings: list[str] = Field(
        default_factory=list,
        description="Data quality advisories related to the queried tables.",
    )
    final_answer: str = Field(..., description="The final synthesized English answer.")
    error_message: str | None = Field(
        default=None, description="Any error encountered during execution."
    )
    cache_hit: bool = Field(
        default=False,
        description="True if the answer was served from the semantic cache.",
    )


class FeedbackRequest(BaseModel):
    question: str
    source_id: str
    generated_sql: str
    tables_used: list[str]
    feedback_score: int = Field(
        default=1, description="1 for thumbs up, -1 for thumbs down."
    )
