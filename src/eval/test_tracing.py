# src/eval/test_tracing.py
import os
from dotenv import load_dotenv
from src.text2sql.agents.graph import run_agentic_text2sql

# Ensure environment variables are loaded
load_dotenv()


def main():
    if os.getenv("LANGCHAIN_TRACING_V2") != "true":
        print(
            "❌ WARNING: LANGCHAIN_TRACING_V2 is not set to 'true' in your .env file."
        )
        return

    print("🔍 Sending query to Agentic Pipeline (LangSmith Tracing Enabled)...")

    # We use a cross-domain question to trigger multiple nodes
    question = "What is the total revenue generated by sellers in SP?"

    res = run_agentic_text2sql(question, source_id="olist")

    print("\n✅ Query Complete!")
    print(f"Final Answer: {res.get('final_answer')}")
    print("\n👉 Now, go to https://smith.langchain.com")
    print(
        "👉 Click on the 'TrustSQL-Demo' project to see the visual trace of this execution!"
    )


if __name__ == "__main__":
    main()
